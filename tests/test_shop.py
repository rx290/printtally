"""PrintTally 2.0 shop layer: materials, mixed-material jobs, parts, licences, royalties, preference files,
and Cura / Orca G-code."""
import json
import pytest
from core import shop, gcode_stats
from core.cost_model import CostInputs, calculate_cost


@pytest.fixture
def lib():
    mats = shop.load_materials(directory=None)
    mats["PETG"].price_per_kg = 2250.0
    mats["PLA"].price_per_kg = 4150.0
    return mats


def test_slicer_names_find_the_right_material(lib):
    assert shop.match_material("Generic PETG", lib).name == "PETG"
    assert shop.match_material("SUNLU PETG 1.75", lib).name == "PETG"      # longest name wins, not PET
    assert shop.match_material("PLA Basic", lib).name == "PLA"
    assert shop.match_material("", lib) is None
    assert shop.match_material("Nylon CF", lib) is None


def test_mixed_materials_add_up_per_material(lib):
    job = shop.price_job({"PETG": 100.0, "PLA": 20.0}, 1.0, settings={"electricity_rate_per_kwh": 50},
                         materials=lib, parts={})
    costs = {name: cost for name, _, cost in job.material_lines}
    assert costs == {"PETG": pytest.approx(225.0), "PLA": pytest.approx(83.0)}
    assert job.breakdown.material_cost == pytest.approx(308.0)


def test_a_prototype_always_has_a_price(lib):
    job = shop.price_job({"PETG": 50.0}, 2.0, prefs={"stage": "prototype"}, materials=lib, parts={})
    assert job.stage == "prototype"
    assert job.breakdown.cost_to_make > 0 and job.breakdown.final_price > job.breakdown.cost_to_make


def test_missing_prices_are_reported_not_guessed(lib):
    lib["PLA"].price_per_kg = 0
    job = shop.price_job({"PLA": 10.0}, 1.0, prefs={"bom": [{"part": "dob_5w", "qty": 2}]}, materials=lib, parts={},
                         settings={"electricity_rate_per_kwh": 0})
    text = " ".join(job.warnings)
    assert "No price for PLA" in text and "dob_5w" in text and "Electricity rate not set" in text
    assert job.breakdown.material_cost == 0 and job.breakdown.hardware_cost == 0


def test_parts_are_priced_into_cost_to_make(lib):
    job = shop.price_job({"PETG": 100.0}, 0.0, prefs={"bom": [{"part": "dob_5w", "qty": 1},
                                                              {"part": "switch", "qty": 2}]},
                         settings={"machine_rate_per_hour": 0, "waste_pct": 0}, materials=lib,
                         parts={"dob_5w": 180.0, "switch": 25.0})
    assert job.breakdown.hardware_cost == pytest.approx(230.0)
    assert job.breakdown.cost_to_make == pytest.approx(225.0 + 230.0)


def test_personal_licence_is_priced_but_flagged_do_not_sell(lib):
    job = shop.price_job({"PETG": 40.0}, 1.0, prefs={"licence": "personal"}, materials=lib, parts={})
    assert not job.sellable and job.warnings[0].startswith("PERSONAL-USE LICENCE")
    assert "DO NOT SELL" in shop.format_job(job)
    assert job.breakdown.final_price > 0


def test_commercial_royalty_share_leaves_the_asked_margin():
    base = calculate_cost(CostInputs(model_weight_g=100, price_per_kg=2000, print_hours=1, profit_margin_pct=.25))
    with_royalty = calculate_cost(CostInputs(model_weight_g=100, price_per_kg=2000, print_hours=1,
                                             profit_margin_pct=.25, royalty_pct=.10, royalty_fixed=20))
    # After the designer takes 10% of the price, what is left equals the price without royalty plus the fixed
    # royalty and its margin.
    left = with_royalty.final_price - with_royalty.royalty_cost + 20
    assert left == pytest.approx(base.final_price + 20 * 1.25, abs=.02)
    with pytest.raises(ValueError):
        calculate_cost(CostInputs(model_weight_g=1, price_per_kg=1, print_hours=1, royalty_pct=1.0))


def test_preference_files_nearest_wins(tmp_path):
    shop_dir = tmp_path / "Lamps"
    dome = shop_dir / "Dome"
    dome.mkdir(parents=True)
    (shop_dir / "printtally.json").write_text(json.dumps({"material": "PETG", "profit_margin_pct": .3,
                                                         "packaging_cost": 50}))
    (dome / "printtally.json").write_text(json.dumps({"profit_margin_pct": .4, "bom": [{"part": "dob_5w"}]}))
    model = dome / "dome_110.stl"
    model.write_text("solid x\nendsolid x\n")
    (dome / "dome_110.printtally.json").write_text(json.dumps({"stage": "selling"}))
    prefs, used = shop.find_preferences(model)
    assert prefs["material"] == "PETG" and prefs["packaging_cost"] == 50          # from the shop folder
    assert prefs["profit_margin_pct"] == .4 and prefs["bom"] == [{"part": "dob_5w"}]  # the Dome folder overrides
    assert prefs["stage"] == "selling"                                              # the model's own file last
    assert used[-1].endswith("dome_110.printtally.json")


ORCA = """; generated by OrcaSlicer
G1 X1
; filament used [mm] = 3700.10, 900.00
; filament used [g] = 11.06, 2.70
; filament_type = PETG;PLA
; estimated printing time (normal mode) = 1h 56m 30s
"""
CURA = """;FLAVOR:Marlin
;TIME:2460
;Filament used: 7.1234m
;Layer height: 0.12
"""


def test_orca_gcode_gives_grams_per_material_and_time(lib):
    st = gcode_stats.parse(ORCA)
    assert st.slicer == "orca/prusa" and st.grams == [11.06, 2.70] and st.materials == ["PETG", "PLA"]
    assert st.hours == pytest.approx(1 + 56 / 60 + 30 / 3600)
    assert gcode_stats.grams_by_material(st, lib) == {"PETG": 11.06, "PLA": 2.70}


def test_cura_gcode_metres_become_grams_of_the_preferred_material(lib):
    st = gcode_stats.parse(CURA)
    assert st.slicer == "cura" and st.hours == pytest.approx(2460 / 3600) and st.metres == [7.1234]
    grams = gcode_stats.grams_by_material(st, lib, default_material="PETG")
    assert grams["PETG"] == pytest.approx(7.1234 * 2.405 * 1.27, rel=.01)   # 1.75 mm: 2.405 mm2 cross-section
    job = shop.price_job(grams, st.hours, prefs={"material": "PETG"}, materials=lib, parts={})
    assert job.material_lines[0][0] == "PETG"


