def test_price_from_slicer_uses_names_preferences_and_plugin_fallback(tmp_path):
    cfg = tmp_path / "cfg"
    cfg.mkdir()
    (cfg / "materials.json").write_text(json.dumps({"PETG": {"price_per_kg": 2250}}))
    (cfg / "parts.json").write_text(json.dumps({"dob_5w": {"price": 180}}))
    model_dir = tmp_path / "Lamps"
    model_dir.mkdir()
    (model_dir / "printtally.json").write_text(json.dumps({"bom": [{"part": "dob_5w"}], "stage": "selling"}))
    model = model_dir / "dome.stl"
    model.write_text("x")
    job = shop.price_from_slicer([100.0, 10.0], ["Generic PETG", "Generic PLA"], 2.0, model,
                                 {"price_per_kg": 3000, "electricity_rate_per_kwh": 40}, directory=cfg)
    costs = {n: c for n, _, c in job.material_lines}
    assert costs["PETG"] == pytest.approx(225.0)          # your materials.json price
    assert costs["PLA"] == pytest.approx(30.0)            # not priced yet: the plugin's price per kg
    assert job.breakdown.hardware_cost == pytest.approx(180.0) and job.stage == "selling"
    assert not any("Electricity rate not set" in w for w in job.warnings)


def test_filament_profile_overrides_slicer_names(tmp_path):
    (tmp_path / "materials.json").write_text(json.dumps({
        "PETG A-grade": {"price_per_kg": 3500, "density_g_cm3": 1.27, "aliases": ["petg a"]},
        "ABS": {"price_per_kg": 4000, "density_g_cm3": 1.04, "aliases": ["abs"]}}))
    auto = shop.price_from_slicer([100.0], ["Generic ABS"], 1.0, None, {}, tmp_path)
    picked = shop.price_from_slicer([100.0], ["Generic ABS"], 1.0, None, {"filament_profile": "PETG A-grade"}, tmp_path)
    assert auto.breakdown.material_cost == 400.0 and picked.breakdown.material_cost == 350.0


def test_weigh_factor_scales_grams(tmp_path):
    import json
    from core.shop import load_materials, price_job
    (tmp_path / "materials.json").write_text(json.dumps({"PETG": {"price_per_kg": 3000, "weigh_factor": 1.1}}))
    mats = load_materials(tmp_path)
    assert mats["PETG"].weigh_factor == 1.1 and mats["PLA"].weigh_factor == 1.0
    job = price_job({"PETG": 100.0}, 1.0, {}, materials=mats, parts={})
    assert abs(job.material_lines[0][1] - 110.0) < 1e-6 and abs(job.material_lines[0][2] - 330.0) < 1e-6


def test_failure_rate_and_monthly_fixed(tmp_path):
    from core.cost_model import CostInputs, calculate_cost
    b = calculate_cost(CostInputs(model_weight_g=360, price_per_kg=2500, print_hours=0, machine_rate_per_hour=0,
                                  printer_watts=0, waste_pct=0, profit_margin_pct=0, failure_rate=0.1))
