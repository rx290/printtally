def test_cli_price_folder_writes_csv(tmp_path, config):
    for name in ("01-a", "02-b"):
        (tmp_path / "packs" / name).mkdir(parents=True)
        write_binary_stl(tmp_path / "packs" / name / "part.stl")
    out = tmp_path / "prices.csv"
    r = subprocess.run([sys.executable, str(CLI), "price-folder", str(tmp_path / "packs" / "01-a"),
                        str(tmp_path / "packs" / "02-b"), "--out", str(out), "--profile", "service", "--night"],
                       capture_output=True, text=True)
    assert r.returncode == 0, r.stderr
    assert "01-a" in r.stdout and "ESTIMATE" in r.stdout and "(2 products)" in r.stdout
    rows = list(csv.DictReader(out.open()))
    assert [x["Product"] for x in rows] == ["01-a", "02-b"]
    assert list(rows[0]) == folder.CSV_FIELDS
    assert float(rows[0]["Price"]) > 0 and rows[0]["Profile"] == "service"
    assert "Night rate not set" in rows[0]["Warnings"]


