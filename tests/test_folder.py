def test_mesh_stats_binary_ascii_and_3mf_agree(tmp_path):
    write_binary_stl(tmp_path / "b.stl")
    write_ascii_stl(tmp_path / "a.stl")
    write_3mf(tmp_path / "c.3mf")
    for st in (folder.stl_stats(tmp_path / "b.stl"), folder.stl_stats(tmp_path / "a.stl"),
               folder.threemf_stats(tmp_path / "c.3mf")):
        assert st["volume_cm3"] == pytest.approx(8.0) and st["area_cm2"] == pytest.approx(24.0)
        assert st["size_mm"] == [20, 20, 20] and st["triangles"] == 12


def test_grams_estimate_is_shell_plus_infill():
    st = {"volume_cm3": 8.0, "area_cm2": 24.0}
    # shell 24 cm2 x 0.1 cm = 2.4 cm3, the other 5.6 cm3 at 15% infill
    assert folder.estimate_grams(st, 1.27, 1.0, 0.15) == pytest.approx((2.4 + 5.6 * .15) * 1.27)
    thin = {"volume_cm3": 1.0, "area_cm2": 100.0}            # a thin wall prints solid
    assert folder.estimate_grams(thin, 1.27, 1.2, 0.15) == pytest.approx(1.27)


