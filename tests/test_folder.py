def cube_triangles(s=20.0):
    v = [(0, 0, 0), (s, 0, 0), (s, s, 0), (0, s, 0), (0, 0, s), (s, 0, s), (s, s, s), (0, s, s)]
    faces = [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7), (0, 1, 5), (0, 5, 4),
             (1, 2, 6), (1, 6, 5), (2, 3, 7), (2, 7, 6), (3, 0, 4), (3, 4, 7)]
    return [[v[i] for i in f] for f in faces]


def write_binary_stl(path, s=20.0):
    tris = cube_triangles(s)
    data = b"\0" * 80 + struct.pack("<I", len(tris))
    for t in tris:
        data += struct.pack("<12fH", 0, 0, 0, *[c for p in t for c in p], 0)
    path.write_bytes(data)


def write_ascii_stl(path, s=20.0):
    lines = ["solid cube"]
    for t in cube_triangles(s):
        lines += ["facet normal 0 0 0", "outer loop"] + [f"vertex {x} {y} {z}" for x, y, z in t] + ["endloop",
                                                                                                    "endfacet"]
    path.write_text("\n".join(lines + ["endsolid cube"]))


def write_3mf(path, s=20.0):
    v = [(0, 0, 0), (s, 0, 0), (s, s, 0), (0, s, 0), (0, 0, s), (s, 0, s), (s, s, s), (0, s, s)]
    faces = [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7), (0, 1, 5), (0, 5, 4),
             (1, 2, 6), (1, 6, 5), (2, 3, 7), (2, 7, 6), (3, 0, 4), (3, 4, 7)]
    model = ('<model xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02"><resources>'
             '<object id="1"><mesh><vertices>' + "".join(f'<vertex x="{x}" y="{y}" z="{z}"/>' for x, y, z in v)
             + "</vertices><triangles>" + "".join(f'<triangle v1="{a}" v2="{b}" v3="{c}"/>' for a, b, c in faces)
             + "</triangles></mesh></object></resources></model>")
    with zipfile.ZipFile(path, "w") as z:
        z.writestr("3D/3dmodel.model", model)


