def test_gcode_beside_an_stl_wins_and_prefs_apply(tmp_path, config):
    pack = tmp_path / "02-lamp"
    pack.mkdir()
    write_binary_stl(pack / "shade.stl")
    (pack / "shade.gcode").write_text(ORCA)
    write_binary_stl(pack / "leg.stl")
    write_binary_stl(pack / "coupon.stl")
    (pack / "printtally.json").write_text(json.dumps({
        "material": "PETG", "copies": {"leg.stl": 4}, "skip": ["coupon.stl"], "product": "Test lamp",
        "bom": [{"part": "dob_5w", "qty": 1}], "estimate": {"shell_mm": 1.0, "infill": 0.15, "grams_per_hour": 10}}))
    row = folder.price_product(pack, "02-lamp")
    leg = (2.4 + 5.6 * .15) * 1.27
    assert row["Product"] == "Test lamp" and row["Source"] == "gcode + mesh"
    assert row["Files"] == "leg.stl x4; shade.gcode"
    assert row["Grams"] == pytest.approx(30 + 4 * leg, abs=.1)
    assert row["Print hours"] == pytest.approx(2 + 4 * leg / 10, abs=.01)
    assert row["Parts cost / unit"] == 60 and row["Material"] == "PETG"
    assert row["Estimate"] == "grams and hours from the mesh" and isinstance(row["Price"], int)


